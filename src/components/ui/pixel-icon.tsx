export type PixelName = keyof typeof SPRITES;

const toPath = (rows: readonly string[]) =>
  rows
    .flatMap((row, y) => [...row].map((c, x) => (c === "#" ? `M${x} ${y}h1v1h-1z` : "")))
    .join("");

const PATHS = Object.fromEntries(Object.entries(SPRITES).map(([k, v]) => [k, toPath(v)])) as Record<PixelName, string>;

export function PixelIcon({ name, className, title }: { name: PixelName; className?: string; title?: string }) {
  return (
    <svg
      viewBox="0 0 12 12"
      className={cn("size-5 shrink-0", className)}
      shapeRendering="crispEdges"
      fill="currentColor"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      <path d={PATHS[name]} />
    </svg>
  );
}

export const categoryIcon = (c: ExpenseCategory): PixelName => c;
export const activityIcon = (a: Activity): PixelName => (a === "other" ? "misc" : a);
